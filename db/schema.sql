-- =====================================================================
-- MaziwaTrack database schema (PostgreSQL / Supabase)
-- Tables: users, batches, payments, audit_logs (3NF), password_resets, login_codes
--
-- How to run: Supabase → SQL Editor → paste this file → Run.
-- Safe to run more than once: it only creates what does not exist yet.
-- The verification queries at the end only read; they change nothing.
-- Supabase gives you one database ("postgres"); tables go in the "public" schema.
-- =====================================================================

-- Everyone who logs in. Only farmers register themselves;
-- grader and admin accounts are added by the system administrator.
CREATE TABLE IF NOT EXISTS users (
  user_id       INTEGER GENERATED BY DEFAULT AS IDENTITY,
  full_name     VARCHAR(100) NOT NULL,
  email         VARCHAR(255) NOT NULL,
  phone         VARCHAR(20)  NOT NULL,
  password_hash TEXT NOT NULL,                       -- bcrypt hash, never the plain password
  role          VARCHAR(10) NOT NULL DEFAULT 'farmer',
  is_active     BOOLEAN NOT NULL DEFAULT TRUE,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT pk_users PRIMARY KEY (user_id),
  CONSTRAINT uq_users_email UNIQUE (email),
  CONSTRAINT uq_users_phone UNIQUE (phone),
  CONSTRAINT chk_users_role CHECK (role IN ('farmer', 'grader', 'admin'))
);

-- One milk delivery. The grader columns stay NULL until the batch is tested.
CREATE TABLE IF NOT EXISTS batches (
  batch_id        INTEGER GENERATED BY DEFAULT AS IDENTITY,
  batch_number    VARCHAR(20) NOT NULL,              -- e.g. MT-20261019-0007
  farmer_id       INTEGER NOT NULL,
  declared_litres NUMERIC(8,2) NOT NULL,
  status          VARCHAR(10) NOT NULL DEFAULT 'recorded',
  delivered_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  grader_id       INTEGER NULL,
  measured_litres NUMERIC(8,2) NULL,
  quality_result  VARCHAR(10) NULL,
  grader_notes    TEXT NULL,
  tested_at       TIMESTAMPTZ NULL,
  CONSTRAINT pk_batches PRIMARY KEY (batch_id),
  CONSTRAINT uq_batches_number UNIQUE (batch_number),
  CONSTRAINT fk_batches_farmer FOREIGN KEY (farmer_id) REFERENCES users (user_id),
  CONSTRAINT fk_batches_grader FOREIGN KEY (grader_id) REFERENCES users (user_id),
  CONSTRAINT chk_batches_status CHECK (status IN ('recorded', 'passed', 'rejected', 'paid')),
  CONSTRAINT chk_quality_result CHECK (quality_result IS NULL OR quality_result IN ('pass', 'reject')),
  CONSTRAINT chk_declared_litres CHECK (declared_litres > 0),
  CONSTRAINT chk_measured_litres CHECK (measured_litres IS NULL OR measured_litres > 0)
);

-- One payment per passed batch.
-- Amount = measured_litres x price_per_litre (calculated, not stored).
CREATE TABLE IF NOT EXISTS payments (
  payment_id        INTEGER GENERATED BY DEFAULT AS IDENTITY,
  batch_id          INTEGER NOT NULL,
  admin_id          INTEGER NOT NULL,
  price_per_litre   NUMERIC(8,2) NOT NULL,
  payment_reference VARCHAR(30) NOT NULL,            -- e.g. PAY-20261018-0009
  email_sent        BOOLEAN NOT NULL DEFAULT FALSE,
  approved_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT pk_payments PRIMARY KEY (payment_id),
  CONSTRAINT uq_payments_batch UNIQUE (batch_id),
  CONSTRAINT uq_payments_reference UNIQUE (payment_reference),
  CONSTRAINT fk_payments_batch FOREIGN KEY (batch_id) REFERENCES batches (batch_id),
  CONSTRAINT fk_payments_admin FOREIGN KEY (admin_id) REFERENCES users (user_id),
  CONSTRAINT chk_price_per_litre CHECK (price_per_litre > 0)
);

-- Who did what, and what changed. Rows are only ever added, never edited.
CREATE TABLE IF NOT EXISTS audit_logs (
  log_id     INTEGER GENERATED BY DEFAULT AS IDENTITY,
  user_id    INTEGER NOT NULL,
  action     VARCHAR(50) NOT NULL,                   -- e.g. LOGIN, RECORD_DELIVERY, APPROVE_PAYMENT
  table_name VARCHAR(50) NULL,
  record_id  INTEGER NULL,
  old_value  JSONB NULL,
  new_value  JSONB NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT pk_audit_logs PRIMARY KEY (log_id),
  CONSTRAINT fk_audit_user FOREIGN KEY (user_id) REFERENCES users (user_id)
);

-- Password reset links (forgot password). Only a hash of the link's token is stored;
-- a link works once and expires after 30 minutes.
CREATE TABLE IF NOT EXISTS password_resets (
  reset_id   INTEGER GENERATED BY DEFAULT AS IDENTITY,
  user_id    INTEGER NOT NULL,
  token_hash CHAR(64) NOT NULL,                      -- SHA-256 of the token in the emailed link
  expires_at TIMESTAMPTZ NOT NULL,
  used_at    TIMESTAMPTZ NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT pk_password_resets PRIMARY KEY (reset_id),
  CONSTRAINT uq_password_resets_token UNIQUE (token_hash),
  CONSTRAINT fk_password_resets_user FOREIGN KEY (user_id) REFERENCES users (user_id)
);

-- 2FA login codes. Only a hash of the 6-digit code is stored;
-- a code works once, expires after 10 minutes and allows 5 wrong tries.
CREATE TABLE IF NOT EXISTS login_codes (
  code_id    INTEGER GENERATED BY DEFAULT AS IDENTITY,
  user_id    INTEGER NOT NULL,
  code_hash  CHAR(64) NOT NULL,                      -- SHA-256 of the emailed code
  attempts   INTEGER NOT NULL DEFAULT 0,
  expires_at TIMESTAMPTZ NOT NULL,
  used_at    TIMESTAMPTZ NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT pk_login_codes PRIMARY KEY (code_id),
  CONSTRAINT fk_login_codes_user FOREIGN KEY (user_id) REFERENCES users (user_id)
);

-- Row Level Security: Supabase publishes every table in "public" through its own web API.
-- With RLS on and no policies, that API can read nothing. Our backend connects as the
-- table owner, so it is not affected.
ALTER TABLE users      ENABLE ROW LEVEL SECURITY;
ALTER TABLE batches    ENABLE ROW LEVEL SECURITY;
ALTER TABLE payments   ENABLE ROW LEVEL SECURITY;
ALTER TABLE audit_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE password_resets ENABLE ROW LEVEL SECURITY;
ALTER TABLE login_codes     ENABLE ROW LEVEL SECURITY;

-- =====================================================================
-- Verification (read-only)
-- Each row's "found" should equal "expected".
-- =====================================================================
SELECT 'Tables' AS what_is_checked, COUNT(*) AS found, 6 AS expected
  FROM information_schema.tables
  WHERE table_schema = 'public'
    AND table_name IN ('users', 'batches', 'payments', 'audit_logs', 'password_resets', 'login_codes')
UNION ALL
SELECT 'Foreign keys', COUNT(*), 7
  FROM information_schema.table_constraints
  WHERE table_schema = 'public' AND constraint_type = 'FOREIGN KEY'
    AND table_name IN ('users', 'batches', 'payments', 'audit_logs', 'password_resets', 'login_codes')
UNION ALL
SELECT 'Check rules', COUNT(*), 6
  FROM information_schema.table_constraints
  WHERE table_schema = 'public' AND constraint_type = 'CHECK'
    AND constraint_name LIKE 'chk\_%'
UNION ALL
SELECT 'Row Level Security on', COUNT(*), 6
  FROM pg_tables
  WHERE schemaname = 'public' AND rowsecurity
    AND tablename IN ('users', 'batches', 'payments', 'audit_logs', 'password_resets', 'login_codes');

-- Columns of each table
SELECT table_name, column_name, data_type, is_nullable, column_default
FROM information_schema.columns
WHERE table_schema = 'public' AND table_name IN ('users', 'batches', 'payments', 'audit_logs', 'password_resets', 'login_codes')
ORDER BY table_name, ordinal_position;

-- Row counts (all 0 until the seed files are run)
SELECT 'users' AS table_name, COUNT(*) AS row_count FROM users
UNION ALL SELECT 'batches', COUNT(*) FROM batches
UNION ALL SELECT 'payments', COUNT(*) FROM payments
UNION ALL SELECT 'audit_logs', COUNT(*) FROM audit_logs
UNION ALL SELECT 'password_resets', COUNT(*) FROM password_resets
UNION ALL SELECT 'login_codes', COUNT(*) FROM login_codes;